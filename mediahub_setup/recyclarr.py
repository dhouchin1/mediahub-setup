"""Recyclarr config generator.

Recyclarr syncs quality profiles, formats, and naming conventions from
the TRaSH Guides (https://trash-guides.info/) into Sonarr and Radarr.

The user picks which profiles to sync in the Settings step. We always
include the quality-definition baseline (file-size thresholds per
resolution) and append the user's chosen quality-profile + custom-format
pair for each *arr.

The generated file lives at ``~/mediahub/config/recyclarr/recyclarr.yml``;
the user can edit it freely after the wizard finishes.
"""

