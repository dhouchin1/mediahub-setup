def default_recyclarr_profiles() -> dict[str, list[str]]:
    """Selection used when the user hasn't picked anything yet."""
    return {"sonarr": ["web-1080p"], "radarr": ["hd-bluray-web"]}


# ---------------------------------------------------------------------------
# Renderer
# ---------------------------------------------------------------------------


def _render_includes(profiles: dict[str, RecyclarrProfile], keys: list[str]) -> list[str]:
    out: list[str] = []
    for key in keys:
        profile = profiles.get(key)
        if not profile:
            continue
        out.append(f"      - template: {profile['quality_profile_template']}")
        out.append(f"      - template: {profile['custom_formats_template']}")
    return out


def render_recyclarr_config(
    *,
    sonarr_internal_url: str,
    sonarr_api_key: str,
    radarr_internal_url: str,
    radarr_api_key: str,
    selected_profiles: dict[str, list[str]] | None = None,
) -> Path:
    """Write ``recyclarr.yml`` under ``~/mediahub/config/recyclarr/``.

    ``selected_profiles`` is ``{"sonarr": [keys…], "radarr": [keys…]}``.
    When None, falls back to :func:`default_recyclarr_profiles`.
    """
    selected = selected_profiles or default_recyclarr_profiles()
    sonarr_keys = selected.get("sonarr") or []
    radarr_keys = selected.get("radarr") or []

    lines: list[str] = [
        "# recyclarr.yml — generated by mediahub-setup",
        "# Edit freely; see https://recyclarr.dev/wiki/yaml/config-reference/",
        "# `recyclarr sync` runs on the cron schedule defined in docker-compose.yml.",
        "",
        "sonarr:",
        "  series:",
        f"    base_url: {sonarr_internal_url}",
        f"    api_key: {sonarr_api_key}",
        "",
        "    include:",
        "      - template: sonarr-quality-definition-series",
        *_render_includes(SONARR_PROFILES, sonarr_keys),
        "",
        "radarr:",
        "  movies:",
        f"    base_url: {radarr_internal_url}",
        f"    api_key: {radarr_api_key}",
        "",
        "    include:",
        "      - template: radarr-quality-definition-movie",
        *_render_includes(RADARR_PROFILES, radarr_keys),
        "",
    ]

    RECYCLARR_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    yml_path = RECYCLARR_CONFIG_DIR / "recyclarr.yml"
    yml_path.write_text("\n".join(lines))
    return yml_path
